  let currentLocale = 'de';

  function pick(lc) {
    const c = String(lc || 'de').toLowerCase();
    if (c.startsWith('ar')) return 'ar';
    if (c.startsWith('en')) return 'en';
    return 'de';
  }

  window.__shamellI18n = {
    t(key) {
      const tbl = STRINGS[currentLocale] || STRINGS.de;
      return tbl[key] !== undefined ? tbl[key] : (STRINGS.de[key] !== undefined ? STRINGS.de[key] : key);
    },
    locale() { return currentLocale; },
    isRTL() { return currentLocale === 'ar'; },
  };

  // Public entry-point called by the Flutter host right after page-load.
  window.__shamellSetLocale = function (lc) {
    currentLocale = pick(lc);
    document.documentElement.lang = currentLocale === 'ar' ? 'ar' : (currentLocale === 'en' ? 'en' : 'de');
    document.documentElement.dir = currentLocale === 'ar' ? 'rtl' : 'ltr';
    // Notify the app to re-render with the new strings.
    if (typeof window.__shamellOnLocaleChange === 'function') {
      try { window.__shamellOnLocaleChange(currentLocale); } catch (_) { /* non-fatal */ }
    }
  };
